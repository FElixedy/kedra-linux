//! SQL schema definitions.
//!
//! Timestamps are stored as ISO-8601 UTC strings (`YYYY-MM-DDTHH:MM:SSZ`),
//! which sort lexicographically in the same order they sort chronologically —
//! so range queries can use a plain index.

/// Migration 1: the complete initial schema.
pub const V1_INITIAL: &str = r#"
-- ---------------------------------------------------------------------------
-- Operations: everything this application did to the system.
-- ---------------------------------------------------------------------------
CREATE TABLE operations (
    id              TEXT PRIMARY KEY,          -- ULID-ish, generated by the engine
    kind            TEXT NOT NULL,             -- system_update, install, remove, ...
    source          TEXT NOT NULL,             -- which page/flow started it
    description     TEXT NOT NULL,
    state           TEXT NOT NULL,             -- queued|running|succeeded|failed|cancelled
    started_at      TEXT,
    finished_at     TEXT,
    requires_reboot INTEGER NOT NULL DEFAULT 0,
    error_kind      TEXT,
    error_message   TEXT,
    -- Structured summary (affected entities, counts, warnings) as JSON.
    summary         TEXT NOT NULL DEFAULT '{}',
    created_at      TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now'))
);
CREATE INDEX idx_operations_started ON operations(started_at DESC);
CREATE INDEX idx_operations_state ON operations(state);

-- Streamed output, kept bounded by the engine rather than growing forever.
CREATE TABLE operation_log (
    operation_id TEXT NOT NULL REFERENCES operations(id) ON DELETE CASCADE,
    seq          INTEGER NOT NULL,
    stream       TEXT NOT NULL,                -- stdout|stderr|status
    line         TEXT NOT NULL,
    PRIMARY KEY (operation_id, seq)
) WITHOUT ROWID;

-- ---------------------------------------------------------------------------
-- Change events: the single normalized timeline behind What Changed?.
-- ---------------------------------------------------------------------------
CREATE TABLE change_events (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    timestamp    TEXT NOT NULL,
    source       TEXT NOT NULL,                -- highest-ranked source seen
    category     TEXT NOT NULL,
    relevance    TEXT NOT NULL,
    title        TEXT NOT NULL,
    description  TEXT,
    metadata     TEXT NOT NULL DEFAULT '{}',   -- ChangeMetadata as JSON
    -- Deterministic identity of the underlying real-world change. Unique, so
    -- two collectors observing one change cannot create two rows.
    dedup_key    TEXT NOT NULL,
    operation_id TEXT REFERENCES operations(id) ON DELETE SET NULL,
    boot_id      TEXT,
    created_at   TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now'))
);
CREATE UNIQUE INDEX idx_change_events_dedup ON change_events(dedup_key);
-- The hot path: "everything between two timestamps, newest first".
CREATE INDEX idx_change_events_timestamp ON change_events(timestamp DESC);
CREATE INDEX idx_change_events_category_time ON change_events(category, timestamp DESC);
CREATE INDEX idx_change_events_relevance_time ON change_events(relevance, timestamp DESC);
CREATE INDEX idx_change_events_boot ON change_events(boot_id);
CREATE INDEX idx_change_events_operation ON change_events(operation_id);

-- Provenance: every source that independently reported the event.
CREATE TABLE change_event_sources (
    event_id INTEGER NOT NULL REFERENCES change_events(id) ON DELETE CASCADE,
    source   TEXT NOT NULL,
    seen_at  TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')),
    PRIMARY KEY (event_id, source)
) WITHOUT ROWID;

-- Objects the event concerns, for lookups like "everything about mesa".
CREATE TABLE change_event_entities (
    event_id    INTEGER NOT NULL REFERENCES change_events(id) ON DELETE CASCADE,
    entity_kind TEXT NOT NULL,
    entity_id   TEXT NOT NULL,
    PRIMARY KEY (event_id, entity_kind, entity_id)
) WITHOUT ROWID;
CREATE INDEX idx_event_entities_lookup ON change_event_entities(entity_kind, entity_id);

-- Precomputed subsystem tags, so correlation queries are an indexed lookup
-- rather than a full-table rule evaluation.
CREATE TABLE change_event_subsystems (
    event_id  INTEGER NOT NULL REFERENCES change_events(id) ON DELETE CASCADE,
    subsystem TEXT NOT NULL,
    affinity  INTEGER NOT NULL,
    PRIMARY KEY (event_id, subsystem)
) WITHOUT ROWID;
CREATE INDEX idx_event_subsystems_lookup ON change_event_subsystems(subsystem, affinity DESC);

-- ---------------------------------------------------------------------------
-- Snapshots: lightweight system metadata, never user data.
-- ---------------------------------------------------------------------------
CREATE TABLE snapshots (
    id             INTEGER PRIMARY KEY AUTOINCREMENT,
    taken_at       TEXT NOT NULL,
    kind           TEXT NOT NULL,              -- pre_operation|post_operation|manual|baseline
    label          TEXT NOT NULL,
    note           TEXT,
    operation_id   TEXT REFERENCES operations(id) ON DELETE SET NULL,
    boot_id        TEXT,
    kernel_release TEXT
);
CREATE INDEX idx_snapshots_taken ON snapshots(taken_at DESC);
CREATE INDEX idx_snapshots_kind ON snapshots(kind);

CREATE TABLE snapshot_packages (
    snapshot_id INTEGER NOT NULL REFERENCES snapshots(id) ON DELETE CASCADE,
    name        TEXT NOT NULL,
    version     TEXT NOT NULL,
    PRIMARY KEY (snapshot_id, name)
) WITHOUT ROWID;

CREATE TABLE snapshot_services (
    snapshot_id  INTEGER NOT NULL REFERENCES snapshots(id) ON DELETE CASCADE,
    unit         TEXT NOT NULL,
    enablement   TEXT NOT NULL,
    active_state TEXT NOT NULL,
    PRIMARY KEY (snapshot_id, unit)
) WITHOUT ROWID;

CREATE TABLE snapshot_dkms (
    snapshot_id    INTEGER NOT NULL REFERENCES snapshots(id) ON DELETE CASCADE,
    module         TEXT NOT NULL,
    module_version TEXT NOT NULL,
    kernel_release TEXT NOT NULL,
    status         TEXT NOT NULL,
    PRIMARY KEY (snapshot_id, module, kernel_release)
) WITHOUT ROWID;

-- Config files: hash and metadata only. Contents are never stored here.
CREATE TABLE snapshot_config (
    snapshot_id    INTEGER NOT NULL REFERENCES snapshots(id) ON DELETE CASCADE,
    path           TEXT NOT NULL,
    hash           TEXT,
    file_kind      TEXT NOT NULL,
    size           INTEGER NOT NULL DEFAULT 0,
    mode           INTEGER NOT NULL DEFAULT 0,
    uid            INTEGER NOT NULL DEFAULT 0,
    gid            INTEGER NOT NULL DEFAULT 0,
    symlink_target TEXT,
    modified       TEXT,
    PRIMARY KEY (snapshot_id, path)
) WITHOUT ROWID;

-- Free-form facts: mesa version, GPU driver, session type, bootloader, ...
CREATE TABLE snapshot_facts (
    snapshot_id INTEGER NOT NULL REFERENCES snapshots(id) ON DELETE CASCADE,
    key         TEXT NOT NULL,
    value       TEXT NOT NULL,
    PRIMARY KEY (snapshot_id, key)
) WITHOUT ROWID;

-- ---------------------------------------------------------------------------
-- Live configuration state, diffed on each scan to emit config change events.
-- ---------------------------------------------------------------------------
CREATE TABLE config_state (
    path           TEXT PRIMARY KEY,
    hash           TEXT,
    file_kind      TEXT NOT NULL,
    size           INTEGER NOT NULL DEFAULT 0,
    mode           INTEGER NOT NULL DEFAULT 0,
    uid            INTEGER NOT NULL DEFAULT 0,
    gid            INTEGER NOT NULL DEFAULT 0,
    symlink_target TEXT,
    modified       TEXT,
    last_seen      TEXT NOT NULL
) WITHOUT ROWID;

-- ---------------------------------------------------------------------------
-- Boot records, so later boots can be compared against earlier ones.
-- ---------------------------------------------------------------------------
CREATE TABLE boot_records (
    boot_id        TEXT PRIMARY KEY,
    booted_at      TEXT NOT NULL,
    kernel_release TEXT NOT NULL,
    firmware_us    INTEGER NOT NULL DEFAULT 0,
    loader_us      INTEGER NOT NULL DEFAULT 0,
    kernel_us      INTEGER NOT NULL DEFAULT 0,
    initrd_us      INTEGER NOT NULL DEFAULT 0,
    userspace_us   INTEGER NOT NULL DEFAULT 0,
    total_us       INTEGER NOT NULL DEFAULT 0,
    failed_units   TEXT NOT NULL DEFAULT '[]',  -- JSON array
    recorded_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now'))
) WITHOUT ROWID;
CREATE INDEX idx_boot_records_time ON boot_records(booted_at DESC);

CREATE TABLE boot_unit_times (
    boot_id     TEXT NOT NULL REFERENCES boot_records(boot_id) ON DELETE CASCADE,
    unit        TEXT NOT NULL,
    duration_us INTEGER NOT NULL,
    PRIMARY KEY (boot_id, unit)
) WITHOUT ROWID;

-- ---------------------------------------------------------------------------
-- Collector bookkeeping: how far each collector has read its source, so a
-- rescan is incremental instead of reparsing years of pacman.log.
-- ---------------------------------------------------------------------------
CREATE TABLE collector_state (
    collector  TEXT PRIMARY KEY,
    cursor     TEXT,               -- opaque: byte offset, journal cursor, timestamp
    last_run   TEXT,
    last_error TEXT
) WITHOUT ROWID;
"#;
